def _rendered(view, request, reader, **kwargs) -> bytes:
    """The bytes the route answers with, as an auditor saves them."""
    force_authenticate(request, user=reader)
    response = view(request, **kwargs)
    assert response.status_code == 200, response.status_code
    response.render()
    return response.content


def _served(dep, action: str, reader) -> bytes:
    path = {"assurance_receipt": "assurance-receipt", "signed_assurance_receipt": "signed-assurance-receipt"}
    request = APIRequestFactory().get(
        f"/api/assurance/deployments/{dep.uuid}/{path[action]}/", HTTP_ACCEPT="application/json"
    )
    return _rendered(DeploymentViewSet.as_view({"get": action}), request, reader, uuid=str(dep.uuid))


def _evidence_file(dep, reader) -> bytes:
    """What an auditor assembles from the API (specification, section 5.3): the
    deployment's findings from the finding list, and each one's uuid, fingerprint and
    evidence rows from its incident pack."""
    factory = APIRequestFactory()
    listed = json.loads(
        _rendered(
            FindingViewSet.as_view({"get": "list"}),
            factory.get("/api/assurance/findings/", {"deployment": str(dep.uuid)}, HTTP_ACCEPT="application/json"),
            reader,
        )
    )
    rows = listed["results"] if isinstance(listed, dict) else listed
    assert not (isinstance(listed, dict) and listed.get("next")), "the fixture fits one page"
    findings = []
    for row in rows:
        pack = json.loads(
            _rendered(
                FindingViewSet.as_view({"get": "incident_pack"}),
                factory.get(f"/api/assurance/findings/{row['uuid']}/incident-pack/", HTTP_ACCEPT="application/json"),
                reader,
                uuid=row["uuid"],
            )
        )
        identity = pack["identity"]["finding"]
        findings.append(
            {"uuid": identity["uuid"], "fingerprint": identity["fingerprint"], "evidence": pack["evidence"]["rows"]}
        )
    return json.dumps({"deployment": str(dep.uuid), "findings": findings}).encode()


def _edited(raw: bytes, edit) -> bytes:
    held = json.loads(raw)
    edit(held)
    return json.dumps(held).encode()


def _members_reversed(value):
    """Every object's members in reverse order. Arrays keep theirs: their order is content."""
    if isinstance(value, dict):
        return {name: _members_reversed(value[name]) for name in reversed(list(value))}
    if isinstance(value, list):
        return [_members_reversed(item) for item in value]
    return value


# ------------------------------------------------- this repository's own verification


def _class_of(refused: receipt.NotAnEnvelope) -> str:
    """``envelope_over``'s refusal, by the words it uses for each kind."""
    said = str(refused)
    if "deeper than" in said or "too deeply" in said:
        return "depth_limit"
    if "DIFFERENT document" in said:
        return "different_document"
    return "not_an_envelope"


def _backend_on_receipt(document: dict, form: str, signed_claim: bool = False) -> str | None:
    try:
        schema = receipt.receipt_schema(document.get("receipt_version"))
    except receipt.UnknownReceiptVersion:
        return "unknown_version"
    if signed_claim and document["receipt_version"] in receipt.NEVER_SIGNED:
        return "never_signed"
    defined, required = set(schema["properties"]), set(schema["required"])
    # What the signed form adds (4.1: the issue time), where this version defines it.
    signed_only = set(receipt.SIGNED_FORM_ONLY) & defined
    if form == "signed":
        defined -= set(receipt.NOT_SIGNED_OVER)
        required = (required - set(receipt.NOT_SIGNED_OVER)) | signed_only
    else:
        defined -= signed_only
    if not required <= document.keys() or not document.keys() <= defined:
        return "malformed"
    for name, rule in schema["properties"].items():
        if "const" in rule and name in document and document[name] != rule["const"]:
            return "malformed"
    # One level into each object member, and 2.0's coverage exactly one of the two
    # shapes 2.0 was emitted in.
    if shapes_read(schema, document) is None:
        return "malformed"
    # From 5.0: the authority chains, each as bad as its worst hop.
    if "authority_chains" in document and receipt.authority_chains_problem(document["authority_chains"]):
        return "malformed"
    # From 6.0: the consequential effects, read against the chains it holds.
    if "consequential_effects" in document and receipt.consequential_effects_problem(
        document["consequential_effects"], document.get("authority_chains")
    ):
        return "malformed"
    outside = ("algorithm", "digest", *receipt.NOT_SIGNED_OVER, *receipt.SIGNED_FORM_ONLY)
    hashed = {k: v for k, v in document.items() if k not in outside}
    if receipt._digest(hashed) != document["digest"]:
        return "digest_mismatch"
    return None


def _backend(artifact: bytes, *, sent: dict | None = None, evidence_of: Deployment | None = None) -> str | None:
    """This repository's answer, in the specification's step order. ``None`` is no
    refusal: every check the backend makes passed -- and a signature is not one of
    them. ``sent`` is the document the backend asked to have signed, which an
    envelope held on its own is compared with, as the route compares it."""
    text = artifact.decode("utf-8")
    if _nesting_depth(text) > MAX_JSON_DEPTH:
        return "depth_limit"
    held = json.loads(text)
    if "envelope" in held:
        envelope, document, form = held["envelope"], held["receipt"], "signed"
    elif "payloadType" in held:
        envelope, document, form = held, sent, "signed"
    else:
        envelope, document, form = None, held, "full"
    if envelope is not None:
        try:
            receipt.envelope_over(document, envelope)
        except receipt.NotAnEnvelope as refused:
            return _class_of(refused)
    answer = _backend_on_receipt(document, form, signed_claim=envelope is not None)
    if answer is None and evidence_of is not None:
        stored = receipt.deployment_receipt(
            Deployment.objects.prefetch_related("findings__evidence").get(pk=evidence_of.pk)
        )
        if (stored["digest"], stored["finding_count"]) != (
            document["evidence"]["root"],
            document["evidence"]["finding_count"],
        ):
            answer = "evidence_mismatch"
    if answer is None and envelope is None:
        # No envelope: the signed route's `envelope: null`, or the unsigned copy, whose
        # own `signed: false` (3.1 on) the schema's constant has already held it to.
        return "unsigned"
    return answer


