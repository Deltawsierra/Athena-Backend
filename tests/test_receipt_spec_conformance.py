"""The Assurance Receipt specification, held to the code it describes (Phase 6).

``docs/receipt-spec/v4.1.md`` says a third party can verify a receipt with nothing
but the specification and ``tools/verify_receipt.py``. This file is what makes that
sentence checkable. Every vector below is GENERATED BY THE REAL CODE -- the real
routes, rendered to the bytes an auditor receives -- and then judged twice:

* by the offline verifier, loaded from its file (it imports nothing from here);
* by this repository's own verification: the functions the backend already has for
  each step and nothing else -- ``_nesting_depth`` (the #111 bound),
  ``receipt_schema`` and ``UnknownReceiptVersion``, the published schema's required
  members and constants, ``_digest``, ``deployment_receipt`` and ``envelope_over``.

The two must give the same answer, verdict and reason, on every vector -- with one
exception that is the code's design and not a gap in this test. THE BACKEND HOLDS NO
KEYRING AND NEVER CHECKS A SIGNATURE (``envelope_over``: "NOT the signature";
``signed_assurance_receipt``: "Verification is the auditor's job"), AND IT HAS NO
FRESHNESS POLICY -- how old is too old is the reader's (``--max-age``). On a vector
whose only defect is the signature or the age, every check the backend makes passes,
so its answer is no refusal, and the verifier is held instead to the ground truth the
vector was built with: which key signed which bytes, and when the backend's clock said
they were issued.

The signer is a stand-in. athena-engine signs receipts (``POST
/api/assurance/receipt/sign``, ``engine/evidence/envelope.py`` ``wrap``) and this
backend does not import the engine, so ``_Engine`` below signs the way the engine
does -- the engine's canonical bytes, DSSE's pre-authentication encoding bound to the
receipt type, Ed25519 -- with keys generated here. No key is read from anywhere, and
none is printed.
"""

