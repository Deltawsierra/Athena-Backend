def _answer(verdict) -> str:
    return "verified" if verdict.verified else verdict.reason


@pytest.mark.django_db
def test_every_vector_gets_the_same_answer_from_the_backend_and_the_offline_verifier(vectors):
    assert list(vectors) == [name for name, _, _ in VECTORS], "the vectors are the ones VECTORS lists"
    table, wrong = [], []
    for name, truth, verifier_only in VECTORS:
        vector = vectors[name]
        verdict = verifier.verify(
            vector.artifact, keyring=vector.keyring, evidence=vector.evidence, max_age=vector.max_age, now=vector.now
        )
        offline = _answer(verdict)
        the_verifiers_alone = verifier_only or truth == "verified"
        backend = vector.backend or (
            "no refusal; signature and age not checked here" if the_verifiers_alone else "no refusal"
        )
        table.append(f"{name:<64} backend: {backend:<48} verifier: {offline}")
        if offline != truth:
            wrong.append(f"{name}: the verifier said {offline}, the vector was built to be {truth}")
        if vector.shows is not None and vector.shows not in verdict.render():
            wrong.append(f"{name}: the verdict does not show {vector.shows!r}:\n{verdict.render()}")
        if the_verifiers_alone:
            # Every check the backend makes passed; the signature and the age are the
            # verifier's alone.
            if vector.backend is not None:
                wrong.append(f"{name}: the backend refused ({vector.backend}) where it has nothing to refuse")
        elif vector.backend != truth:
            wrong.append(f"{name}: the backend said {vector.backend}, the verifier {offline}")
    print("\n" + "\n".join(table))
    assert not wrong, "\n".join(wrong) + "\n\n" + "\n".join(table)


@pytest.mark.django_db
def test_the_digest_and_the_signed_payload_are_two_canonical_forms(vectors):
    """Section 5.1 and 6.2, on the real receipt: the digest is taken over ASCII with
    every non-ASCII character escaped; the signed payload is raw UTF-8. A verifier
    that used either form for both would pass neither test above."""
    signed = json.loads(vectors["signed receipt"].artifact)
    payload = base64.b64decode(signed["envelope"]["payload"])
    assert "Zürich".encode() in payload and b"\\u00fc" not in payload
    # The issue time is in the signed payload and outside the digest.
    assert b'"issued_at":"' + ISSUED_TEXT.encode() + b'"' in payload
    outside = ("algorithm", "digest", *receipt.SIGNED_FORM_ONLY)
    hashed = {k: v for k, v in signed["receipt"].items() if k not in outside}
    digest_form = json.dumps(hashed, sort_keys=True, separators=(",", ":")).encode()
    assert b"Z\\u00fcrich" in digest_form
    assert hashlib.sha256(digest_form).hexdigest() == signed["receipt"]["digest"] == receipt._digest(hashed)


@pytest.mark.django_db
def test_the_verifier_runs_as_a_program_from_anywhere(vectors, tmp_path):
    """``python -I``: no PYTHON* variables, no user site, and not this repository or
    the script's own directory on the path -- so a pass here is a pass with the
    standard library and ``cryptography`` alone. Exit status 0, 1 and 2."""
    def run(*files: tuple[str, bytes], flags: tuple[str, ...] = ()) -> subprocess.CompletedProcess:
        for name, data in files:
            (tmp_path / name).write_bytes(data)
        return subprocess.run(
            [sys.executable, "-I", str(VERIFIER_PATH), files[0][0], *flags],
            cwd=tmp_path, capture_output=True, text=True, timeout=60, check=False,
        )

    good = vectors["signed receipt"]
    verified = run(("signed.json", good.artifact), ("ring.json", good.keyring), flags=("--keyring", "ring.json"))
    assert verified.returncode == 0, verified.stderr
    assert verified.stdout.splitlines()[0] == "VERIFIED"
    assert "integrity and provenance only" in verified.stdout

    altered = run(("altered.json", vectors["unsigned copy, the decision altered"].artifact))
    assert altered.returncode == 1, altered.stderr
    assert altered.stdout.splitlines()[0] == "REFUSED digest_mismatch"

    no_key = run(("signed.json", good.artifact))
    assert no_key.returncode == 2 and no_key.stderr.startswith("CANNOT RUN:")
    assert no_key.stdout == ""

    public_key = next(iter(json.loads(good.keyring)["keys"].values()))["public_key"]
    by_key = run(("signed.json", good.artifact), ("key.b64", public_key.encode()), flags=("--public-key", "key.b64"))
    assert by_key.returncode == 0, by_key.stderr

    missing = run(("signed.json", good.artifact), flags=("--keyring", "nowhere.json"))
    assert missing.returncode == 2 and "cannot read nowhere.json" in missing.stderr

    # --max-age against this machine's own clock. The receipt was issued at ISSUED, in
    # the past, so a minute is too old and a century is not.
    ring = ("--keyring", "ring.json")
    stale = run(("signed.json", good.artifact), ("ring.json", good.keyring), flags=(*ring, "--max-age", "60"))
    assert stale.returncode == 1, stale.stderr
    assert stale.stdout.splitlines()[0] == "REFUSED stale"
    fresh = run(("signed.json", good.artifact), ("ring.json", good.keyring), flags=(*ring, "--max-age", "3155760000"))
    assert fresh.returncode == 0, fresh.stderr
    assert f"issued at {ISSUED_TEXT} by the issuer's clock" in fresh.stdout
    four_oh = vectors["signed 4.0 receipt under --max-age"].artifact
    untimed = run(("four.json", four_oh), ("ring.json", good.keyring), flags=(*ring, "--max-age", "3155760000"))
    assert untimed.returncode == 1, untimed.stderr
    assert untimed.stdout.splitlines()[0] == "REFUSED no_signed_time"
    negative = run(("signed.json", good.artifact), ("ring.json", good.keyring), flags=(*ring, "--max-age", "-1"))
    assert negative.returncode == 2 and negative.stderr.startswith("CANNOT RUN:")


