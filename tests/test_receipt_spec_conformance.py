# ----------------------------------------------------------------- building blocks


def _b64(data: bytes) -> str:
    return base64.b64encode(data).decode("ascii")


def _raw_public(key: Ed25519PrivateKey) -> bytes:
    return key.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)


def _key_id(key: Ed25519PrivateKey) -> str:
    return "sha256:" + hashlib.sha256(_raw_public(key)).hexdigest()[:32]


def _sign(body: bytes, key: Ed25519PrivateKey, payload_type: str = receipt.ASSURANCE_RECEIPT_TYPE) -> dict:
    """A DSSE envelope over exactly ``body``, as the engine's ``wrap`` builds one."""
    kind = payload_type.encode("utf-8")
    pae = b" ".join([b"DSSEv1", str(len(kind)).encode(), kind, str(len(body)).encode(), body])
    return {
        "envelope_version": 1,
        "payloadType": payload_type,
        "payload": _b64(body),
        "signatures": [{"keyid": _key_id(key), "sig": _b64(key.sign(pae))}],
    }


def _engine_bytes(document: dict) -> bytes:
    """The engine's canonical bytes (``engine.evidence.envelope.canonical_bytes``):
    sorted keys, no whitespace, raw UTF-8 -- NOT the digest's ASCII-escaped form."""
    return json.dumps(document, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8")


class _Engine:
    """Stands in for the engine's signing route; see the module docstring."""

    def __init__(self, key: Ed25519PrivateKey | None = None, *, payload=None, fails: Exception | None = None):
        self.key, self.payload, self.fails, self.sent = key, payload, fails, None

    def sign_assurance_receipt(self, document):
        if self.fails is not None:
            raise self.fails
        self.sent = document
        return _sign(self.payload if self.payload is not None else _engine_bytes(document), self.key)


def _keyring(*entries: tuple[Ed25519PrivateKey, str]) -> bytes:
    """A keyring as the engine publishes it at ``GET /api/assurance/keyring``,
    ``caveat`` included."""
    keys = {
        _key_id(key): {
            "public_key": _b64(_raw_public(key)),
            "status": status,
            "created_at": None,
            "retired_at": None,
            "reason": None,
        }
        for key, status in entries
    }
    caveat = (
        "a retired key still verifies receipts it signed; a revoked key verifies nothing, "
        "and every receipt signed with it is invalid"
    )
    return json.dumps({"version": 1, "keys": keys, "caveat": caveat}).encode()


